//! Check an unsaved entry-point rename against rust-analyzer's Cargo project model.

use super::*;
use tree_sitter::{Node, Parser};

/// The two project queries share the overlay revision and deadline of the native pull.
pub(super) enum Check {
    Native,
    CrateRoot(Value),
    Binary(Value),
}

impl Client {
    /// Publish native results immediately, then confirm any missing entry on the same revision.
    pub(super) fn diagnostic_response(
        &mut self,
        request: DiagnosticRequest,
        check: Check,
        result: &mut Value,
        event: &impl Fn(Event),
    ) -> Result<()> {
        let Some(open) = self
            .documents
            .get_mut(&request.uri)
            .filter(|open| open.version == request.version && Instant::now() < request.deadline)
        else {
            return Ok(());
        };
        let document = json!({"uri":request.uri});
        let (next, method, params) = match check {
            Check::Native => {
                let Some(mut items) = diagnostic_items(self.server, result) else {
                    return Ok(());
                };
                items.truncate(512);
                open.report_diagnostics(items, event);
                let Some(rust) = &open.rust_diagnostics else {
                    return Ok(());
                };
                if rust.binary_root == Some(false) {
                    return Ok(());
                }
                let Some(range) = missing_entry_range(rust.disk.as_deref(), &open.snapshot.text)
                else {
                    return Ok(());
                };
                if rust.binary_root == Some(true) {
                    (
                        Check::Binary(range),
                        "experimental/runnables",
                        json!({"textDocument":document}),
                    )
                } else {
                    (
                        Check::CrateRoot(range),
                        "experimental/parentModule",
                        json!({"textDocument":document,"position":{"line":0,"character":0}}),
                    )
                }
            }
            Check::CrateRoot(range) => {
                // At a Cargo crate root the parent is its manifest. An ordinary module's parent is Rust source.
                let manifest = result.as_array().into_iter().flatten().any(|link| {
                    link.get("targetUri")
                        .or_else(|| link.get("uri"))
                        .and_then(Value::as_str)
                        .and_then(uri_path)
                        .is_some_and(|path| {
                            path.file_name().is_some_and(|name| name == "Cargo.toml")
                        })
                });
                if !manifest {
                    if let Some(rust) = &mut open.rust_diagnostics {
                        if result.as_array().is_some_and(|links| !links.is_empty()) {
                            rust.binary_root = Some(false);
                        }
                        if rust.entry.take().is_some() {
                            rust.publish(&open.snapshot, event)
                        }
                    }
                    return Ok(());
                }
                (
                    Check::Binary(range),
                    "experimental/runnables",
                    json!({"textDocument":document}),
                )
            }
            Check::Binary(range) => {
                let Some(rust) = &mut open.rust_diagnostics else {
                    return Ok(());
                };
                let Some(runnables) = result.as_array() else {
                    return Ok(());
                };
                // A binary target has a package-level cargo run even after its entry disappears.
                // A located run still identifies a real entry (including one generated by a macro).
                let mut binary = false;
                let mut entry = false;
                for runnable in runnables {
                    if runnable["args"]["cargoArgs"][0] == "run" {
                        if runnable["location"].is_null() {
                            binary = true
                        } else {
                            entry = true
                        }
                    }
                }
                if binary
                    || runnables.iter().any(|r| {
                        r["args"]["cargoArgs"][0] == "check"
                            && r["args"]["cargoArgs"][1] == "--package"
                    })
                {
                    rust.binary_root = Some(binary);
                }
                rust.entry = (binary && !entry).then(|| {
                    json!({
                        "range":range, "severity":1, "code":"E0601", "source":"nanobug",
                        "message":"`main` function not found in this binary crate"
                    })
                });
                rust.publish(&open.snapshot, event);
                return Ok(());
            }
        };
        self.diagnostic_serial += 1;
        let id = format!("diagnostics-{}", self.diagnostic_serial);
        self.send(json!({"jsonrpc":"2.0","id":id,"method":method,"params":params}))?;
        self.diagnostic_requests.insert(id, (request, next));
        Ok(())
    }
}

/// Choose the renamed declaration if identifiable, or use the final source position as rustc does.
/// A library or a module can have the same syntax; the subsequent Cargo queries establish its role.
fn missing_entry_range(saved: Option<&str>, edited: &str) -> Option<Value> {
    if saved == Some(edited) {
        return None;
    }
    let mut parser = Parser::new();
    parser
        .set_language(&tree_sitter_rust::LANGUAGE.into())
        .ok()?;
    let after = parser.parse(edited, None)?;
    if after.root_node().has_error() {
        return None;
    }
    let new = root_functions(after.root_node(), edited)?;
    if new.iter().any(|&(name, _)| name == "main") {
        return None;
    }
    let renamed = saved.filter(|text| text.contains("main")).and_then(|text| {
        let before = parser.parse(text, None)?;
        let old: BTreeSet<_> = root_functions(before.root_node(), text)?
            .into_iter()
            .map(|(name, _)| name)
            .collect();
        if !old.contains("main") {
            return None;
        }
        let mut added = new.iter().filter(|(name, _)| !old.contains(name));
        let (_, name) = added.next()?;
        added.next().is_none().then(|| name.byte_range())
    });
    let end = edited.trim_end().len();
    let range = renamed.unwrap_or(end..end);
    Some(json!({"start":position_at(edited, range.start)?, "end":position_at(edited, range.end)?}))
}

/// Keep top-level functions and leave alternative entry mechanisms to the compiler.
fn root_functions<'a, 'tree>(
    root: Node<'tree>,
    text: &'a str,
) -> Option<Vec<(&'a str, Node<'tree>)>> {
    let mut functions = Vec::new();
    for item in root.named_children(&mut root.walk()) {
        let source = &text[item.byte_range()];
        match item.kind() {
            "inner_attribute_item" if source.contains("no_main") => return None,
            // An include or a module-level macro may supply the entry from another source file.
            "macro_invocation" | "expression_statement" => return None,
            "use_declaration"
                if source
                    .split(|c: char| !c.is_alphanumeric() && c != '_')
                    .any(|name| name == "main")
                    || source.contains('*') =>
            {
                return None;
            }
            "function_item" => {
                let name = item.child_by_field_name("name")?;
                let spelling = &text[name.byte_range()];
                functions.push((spelling.strip_prefix("r#").unwrap_or(spelling), name));
            }
            _ => {}
        }
    }
    Some(functions)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn entry_ranges_use_utf16_and_defer_alternative_entries_to_cargo() {
        let saved = "/*🌱*/ fn main() {}";
        for replacement in ["mai", "man", "min", "ain", "启动"] {
            let text = saved.replace("main", replacement);
            let range = missing_entry_range(Some(saved), &text).unwrap();
            let start = offset_at(&text, &range["start"]).unwrap();
            let end = offset_at(&text, &range["end"]).unwrap();
            assert_eq!(&text[start..end], replacement);
        }
        for alternative in [
            "fn r#main() {}",
            "#![no_main]\nfn mai() {}",
            "#![cfg_attr(windows, no_main)]\nfn mai() {}",
            "use app::start as main;",
            "include!(\"entry.rs\");",
            "make_entry!();",
        ] {
            assert!(
                missing_entry_range(Some(saved), alternative).is_none(),
                "{alternative}"
            );
        }
    }
}
